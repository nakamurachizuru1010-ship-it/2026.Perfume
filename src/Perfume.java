
public class Perfume {
	private int id;
	private String name;
	private String detail;

	public Perfume(int i, String n, String d) {
		super();
		this.id = i;
		this.name = n;
		this.detail = d;
	}

	public int getId() {
		return id;
	}

	public String getName() {
		return name;
	}

	public String getDetail() {
		return detail;
	}

}
